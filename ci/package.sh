#!/usr/bin/env bash
# Builds dist/<Addon>-<version>.zip with the addon folder at the top level, which is the
# layout CurseForge and the game expect. The sound pack is generated here (it is ~67 MB of
# OGGs and gitignored), so this needs: pip install -r tools/requirements.txt
# No ROMs are ever packaged: games come from separate ROM pack addons the player makes.
set -euo pipefail
cd "$(dirname "$0")/.."

ADDON_DIR="${ADDON_DIR:-ForeverGBPlayer}"
TOC="$ADDON_DIR/$ADDON_DIR.toc"
PY="${PYTHON:-python3}"

if [[ -n "${CI_COMMIT_TAG:-}" ]]; then
  version="${CI_COMMIT_TAG#v}"
else
  toc_version="$(grep -m1 '^## Version:' "$TOC" | sed 's/^## Version:[[:space:]]*//; s/\r$//')"
  version="${toc_version}-dev.${CI_COMMIT_SHORT_SHA:-local}"
fi

echo "== Generating the sound pack =="
"$PY" tools/make_sound_pack.py # (re)writes the shared pack; leaves local per-game wave packs alone

stage_dir="$(mktemp -d)"
trap 'rm -rf "$stage_dir"' EXIT

cp -R "$ADDON_DIR" "$stage_dir/$ADDON_DIR"
# The ROM converter ships with the addon so players can make ROM packs without any setup:
# double-click it, it runs offline in their browser (WoW ignores .html files in addon folders).
# The source is an artifact page body; give the shipped copy a full document (UTF-8, standards mode).
{
  echo '<!doctype html>'
  echo '<html lang="en"><head><meta charset="utf-8">'
  echo '<meta name="viewport" content="width=device-width, initial-scale=1"></head><body>'
  cat tools/rom-converter.html
  echo '</body></html>'
} > "$stage_dir/$ADDON_DIR/ROM Converter.html"
[[ -f LICENSE ]] && cp LICENSE "$stage_dir/$ADDON_DIR/LICENSE"

# Strip anything that shouldn't ship to players.
find "$stage_dir" \( -name '.*' -o -name '*.bak' -o -name '*.orig' -o -name '*.tmp' \) \
  -not -path "$stage_dir" -exec rm -rf {} + 2>/dev/null || true
# Per-game wave packs from a developer's machine never ship (only the triangle fallback does).
find "$stage_dir/$ADDON_DIR/sound/wave" -name 'w*_*.ogg' ! -name 'wtri_*' -delete
printf -- '-- Generated by tools/make_wave_pack.py: wave RAM pattern (hex) -> sample set id.\nGBSoundWaves = GBSoundWaves or {}\n' \
  > "$stage_dir/$ADDON_DIR/sound/waves.lua"

mkdir -p dist
zip_name="${ADDON_DIR}-${version}.zip"
rm -f "dist/$zip_name"
(cd "$stage_dir" && zip -rq9 "$OLDPWD/dist/$zip_name" "$ADDON_DIR")

echo "$version"  > dist/VERSION
echo "$zip_name" > dist/ZIP_NAME

files="$(unzip -Z1 "dist/$zip_name" | grep -vc '/$')"
echo "Built dist/$zip_name: $files files, $(du -h "dist/$zip_name" | cut -f1)"
unzip -Z1 "dist/$zip_name" | grep -v '^ForeverGBPlayer/sound/' || true
echo "(+ $(unzip -Z1 "dist/$zip_name" | grep -c '^ForeverGBPlayer/sound/.*\.ogg$') sound files under $ADDON_DIR/sound/)"
