#!/usr/bin/env bash
# Fast checks run on every pipeline: Lua syntax, every TOC's file list and version, and
# (on tags) that the tag matches the TOC version. The full emulator test suite is ci/test.sh.
set -euo pipefail

ADDON_DIR="${ADDON_DIR:-ForeverGBPlayer}"
TOC="$ADDON_DIR/$ADDON_DIR.toc"
fail=0

[[ -f "$TOC" ]] || { echo "ERROR: $TOC not found"; exit 1; }

echo "== Lua 5.1 syntax check =="
while IFS= read -r -d '' f; do
  if ! luac5.1 -p "$f"; then
    fail=1
  fi
done < <(find "$ADDON_DIR" src -name '*.lua' -print0)

toc_field() { grep -m1 "^## $2:" "$1" | sed "s/^## $2:[[:space:]]*//; s/\r\$//"; }

toc_version="$(toc_field "$TOC" Version)"
echo "TOC version: ${toc_version:-<missing>}"
[[ "$toc_version" =~ ^[0-9]+\.[0-9]+\.[0-9]+$ ]] || { echo "ERROR: '## Version:' in $TOC must be X.Y.Z"; fail=1; }

# One TOC per client flavor (ForeverGBPlayer_TBC.toc, ..._Camelot.toc).
for toc in "$ADDON_DIR"/*.toc; do
  echo "== $toc =="
  # Every non-comment, non-blank line in the TOC is a file the game will load.
  while IFS= read -r line; do
    line="${line%$'\r'}"
    [[ -z "$line" || "$line" == \#* ]] && continue
    rel="$(printf '%s' "$line" | sed 's#\\#/#g')"
    if [[ "$rel" == sound/* ]]; then
      continue # the sound pack is generated by ci/package.sh (tools/make_sound_pack.py)
    fi
    if [[ ! -f "$ADDON_DIR/$rel" ]]; then
      echo "ERROR: $toc lists '$line' but $ADDON_DIR/$rel does not exist"
      fail=1
    fi
  done < "$toc"
  v="$(toc_field "$toc" Version)"
  if [[ "$v" != "$toc_version" ]]; then
    echo "ERROR: $toc has version '${v:-<missing>}', $TOC has '$toc_version'. Keep them the same."
    fail=1
  fi
  [[ -n "$(toc_field "$toc" Interface)" ]] || { echo "ERROR: no '## Interface:' line in $toc"; fail=1; }
done

echo "== No ROMs in the addon =="
# ROMs ship as separate, user-made ROM pack addons and must never be part of a release.
if find "$ADDON_DIR" -iname '*.gb' -o -iname '*.gbc' -o -iname '*.gba' | grep -q .; then
  echo "ERROR: ROM files found inside $ADDON_DIR:"; find "$ADDON_DIR" -iname '*.gb*'
  fail=1
fi
if packs="$(grep -rl "rom2lua from" "$ADDON_DIR")"; then
  echo "ERROR: converted ROMs (ROM pack Lua) are inside $ADDON_DIR:"; echo "$packs"
  fail=1
fi

if [[ -n "${CI_COMMIT_TAG:-}" ]]; then
  echo "== Tag check =="
  tag_version="${CI_COMMIT_TAG#v}"
  tag_version="${tag_version%%-*}" # drop -beta.1 / -alpha.1
  if [[ "$tag_version" != "$toc_version" ]]; then
    echo "ERROR: tag $CI_COMMIT_TAG does not match TOC version $toc_version."
    echo "       Update '## Version:' in every $ADDON_DIR/*.toc, commit, and re-tag."
    fail=1
  fi
fi

if (( fail )); then
  echo "Validation failed."
  exit 1
fi
echo "All checks passed."
