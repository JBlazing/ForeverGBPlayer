"""Record which wave-channel (channel 3) patterns a game plays, and render samples for them.

Channel 3 plays a game-defined 32-step waveform, so there is no fixed pack that covers
every game. This runs the ROM offline with a simple input script (press Start, run right,
jump), records every wave RAM pattern heard while channel 3 is on, renders
sound/wave/w{id}_{midi}_{level}.ogg for each new pattern, and registers it in
sound/waves.lua (GBSoundWaves[hex] = id), which the addon loads. Patterns it never heard
fall back to a triangle wave in game. Longer --seconds covers more of the game's music.

    py tools/make_wave_pack.py "path/to/game.gb" --seconds 120
"""
import argparse
import hashlib
import pathlib
import re
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
from make_sound_pack import OUT, write_wave_set  # noqa: E402
from sound_preview import scripted_input  # noqa: E402
from test_ppu import boot  # noqa: E402

MANIFEST = OUT / "waves.lua"
LINE = re.compile(r'^GBSoundWaves\["([0-9a-f]{32})"\] = "([0-9a-z]+)"')


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("rom", type=pathlib.Path)
    ap.add_argument("--seconds", type=float, default=120)
    ap.add_argument("--start-at", type=float, default=2.7)
    args = ap.parse_args()

    lua, core = boot(args.rom)
    heard = {}
    start_f = int(args.start_at * 60)
    for f in range(int(args.seconds * 60)):
        scripted_input(core, f, start_f)
        core.RunFrame()
        s = core.GetAudioState()[3]
        if s.on and s.vol > 0:
            heard[s.wave] = heard.get(s.wave, 0) + 1
    print(f"{args.rom.name}: channel 3 used {len(heard)} wave pattern(s) in {args.seconds:.0f}s")

    known = {}
    if MANIFEST.exists():
        for line in MANIFEST.read_text().splitlines():
            m = LINE.match(line)
            if m:
                known[m.group(1)] = m.group(2)
    for hexs, frames in sorted(heard.items(), key=lambda kv: -kv[1]):
        wid = hashlib.sha1(hexs.encode()).hexdigest()[:8]
        status = "known"
        if hexs not in known:
            count, size = write_wave_set(hexs.upper(), wid)
            known[hexs] = wid
            status = f"rendered {count} files ({size / 1e6:.1f} MB)"
        print(f"  {hexs}  id {wid}  {frames:5d} frames  {status}")

    lines = ["-- Generated by tools/make_wave_pack.py: wave RAM pattern (hex) -> sample set id.",
             "GBSoundWaves = GBSoundWaves or {}"]
    lines += [f'GBSoundWaves["{h}"] = "{i}"' for h, i in sorted(known.items())]
    MANIFEST.write_text("\n".join(lines) + "\n", encoding="ascii", newline="\n")
    print(f"{MANIFEST} lists {len(known)} pattern(s)")


if __name__ == "__main__":
    main()
